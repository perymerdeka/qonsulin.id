assert.equal(opening.error, null);
assert.equal(opening.data.status, "pending");
await adminClient.from("letters").update({ moderation_status: "approved", reviewed_at: new Date().toISOString() }).eq("id", opening.data.letter_id);
const pool = await adminClient.from("letters").select("id").eq("id", opening.data.letter_id).eq("moderation_status", "approved");
assert.equal(pool.data.length, 1, "approved opening must be visible");
const reply = await b.client.rpc("send_reply_letter", { p_thread_id: opening.data.thread_id, p_content: "Balasan penguat dari sahabat anonim untuk kawan cerita.", p_template_code: "vintage_parchment", p_reply_type: "community" });
