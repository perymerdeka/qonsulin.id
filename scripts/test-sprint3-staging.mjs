import assert from "node:assert/strict";
import { createClient } from "@supabase/supabase-js";
const URL = process.env.SUPABASE_URL;
const KEY = process.env.SUPABASE_PUBLISHABLE_KEY;
const SERVICE = process.env.SUPABASE_SERVICE_ROLE_KEY;
const adminClient = createClient(URL, SERVICE, { auth: { persistSession: false, autoRefreshToken: false } });
async function createUser(email, alias) {
  const admin = await adminClient.auth.admin.createUser({ email, password: "pass123#", email_confirm: true, user_metadata: { alias, avatar_config: { mood: "smile", bg: "sky", glasses: false } } });
  assert.ifError(admin.error);
  const anon = createClient(URL, KEY, { auth: { persistSession: false, autoRefreshToken: false } });
  const { data: session, error: signInErr } = await anon.auth.signInWithPassword({ email, password: "pass123#" });
  assert.ifError(signInErr);
  const client = createClient(URL, KEY, { auth: { persistSession: false, autoRefreshToken: false }, global: { headers: { Authorization: `Bearer ${session.session.access_token}` } } });
  return { id: session.user.id, client };
}
const ts = Date.now();
const a = await createUser(`s3.a.${ts}@qonsulin.test`, `A_${ts.toString().slice(-4)}`);
const b = await createUser(`s3.b.${ts}@qonsulin.test`, `B_${ts.toString().slice(-4)}`);
const c = await createUser(`s3.c.${ts}@qonsulin.test`, `C_${ts.toString().slice(-4)}`);
